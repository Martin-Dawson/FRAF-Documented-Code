        first_pair_layer = None
        if init_fp_enable and init_fp_mode == 1 and len(chans_sorted) >= 2 and not overlap_cache.has("OCC", "INITPAIR"):
            feedback.pushInfo("[INIT_FP] Preparing first-pair union overlay for cached baseline calculation.")
