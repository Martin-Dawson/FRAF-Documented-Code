# Repair input geometries when the native fix-geometries algorithm is available, otherwise pass the original layer through.
def _fix_geoms(layer, context, feedback):
    lyr = _as_layer(layer, context)
    if not lyr:
        return layer
    if not _algo_exists("native:fixgeometries"):
        return lyr
    out = _run("native:fixgeometries", {"INPUT": lyr, "OUTPUT": "TEMPORARY_OUTPUT"}, context, feedback)["OUTPUT"]
    return _as_layer(out, context) or out

# Strip Z/M where supported so planar GEOS intersections operate on two-dimensional PLACE footprints.
def _force_2d(layer, context, feedback):
    lyr = _as_layer(layer, context)
    if not lyr:
        return layer
    if not _algo_exists("native:force2d"):
        return lyr
    out = _run("native:force2d", {"INPUT": lyr, "OUTPUT": "TEMPORARY_OUTPUT"}, context, feedback)["OUTPUT"]
    return _as_layer(out, context) or out

# Combine geometry repair and 2D conversion before polygon overlay operations.
def _prep_poly(layer, context, feedback):
    return _force_2d(_fix_geoms(layer, context, feedback), context, feedback)

