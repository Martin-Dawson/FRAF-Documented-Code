            if ea_layer.fields().indexOf(ea_field) < 0:
                feedback.reportError(f"[EA] Field '{ea_field}' not found in {ea_layer.name()}. Storing zero checkpoints.")
                for prefix in ("E", "D", "S"):
                    overlap_cache.save("EA", f"{prefix}_{ii:03d}", {})
                continue

