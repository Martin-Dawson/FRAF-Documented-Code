                reactivate_confirmed = 1 if (reactivate_evt == 1 and e_evt_raw == 1) else 0
                storage_confirmed = 1 if (storage_evt == 1 and d_evt_raw == 1) else 0
                stabilise_confirmed = 1 if (stabilise_evt == 1 and stabilised_by_rule == 1) else 0
                storage_rework_confirmed = 1 if (storage_rework_evt == 1 and e_evt_raw == 1) else 0
