# Infer EA interval endpoints from layer naming conventions, with a general date-pair fallback for legacy names.
def _parse_interval_from_layer_name(name):
    s = str(name)
    m = re.search(
        r"EA_processes_(\d{4})\D(\d{2})\D(\d{2})\D(\d{4})\D(\d{2})\D(\d{2})",
        s
    )
    if m:
        y1 = f"{m.group(1)}{m.group(2)}{m.group(3)}"
        y2 = f"{m.group(4)}{m.group(5)}{m.group(6)}"
        return (y1, y2)

    m = re.search(r"EA_processes_((?:18|19|20)\d{6})\D+((?:18|19|20)\d{6})", s)
    if m:
        return (m.group(1), m.group(2))

    dates = re.findall(r"(?:18|19|20)\d{6}", s)
    if len(dates) >= 2:
        return (dates[-2], dates[-1])

    return None

# Filter prepared EA polygons by case-normalised class labels, e.g. erosion/island_erosion or deposition/island_deposition.
def _extract_ea_subset(ea_layer, ea_field, classes, context, feedback, prepare=True):
    lyr = _prep_poly(ea_layer, context, feedback) if prepare else _as_layer(ea_layer, context)
    if not lyr or not lyr.isValid():
        return lyr

    vals = [str(v).strip().lower() for v in (classes or []) if str(v).strip()]

    if not vals:
        expr = "FALSE"
    else:
        def _sql_quote(s):
            return "'" + str(s).replace("'", "''") + "'"

        vals_sql = ",".join(_sql_quote(v) for v in vals)
        expr = f'lower(trim("{ea_field}")) IN ({vals_sql})'

    if feedback:
        feedback.pushInfo(f"[EA] extract expr: {expr}")

    out = _run(
        "native:extractbyexpression",
        {"INPUT": lyr, "EXPRESSION": expr, "OUTPUT": "TEMPORARY_OUTPUT"},
        context, feedback
    )["OUTPUT"]

    return _as_layer(out, context) or out

# Sanitise output table/layer names to portable GeoPackage-compatible identifiers, capped at 60 characters.
def _safe_layername(name: str) -> str:
    s = re.sub(r"[^0-9A-Za-z_]+", "_", str(name))
    s = re.sub(r"_+", "_", s).strip("_")
    return (s or "layer")[:60]

# Derive a regular hexagon spacing whose nominal area equals that of a square of the requested side length.
def _hex_spacing_area_equivalent(square_side):
    s = float(square_side)
    A = s * s
    # For regular hexagons A = 3*sqrt(3)/2 * side**2; solve for side and centre spacings.
    a = math.sqrt((2.0 * A) / (3.0 * math.sqrt(3.0)))  # hex side
    h = 1.5 * a
    v = math.sqrt(3.0) * a
    return h, v, a

# Apply the user-selected event rule to EA overlap proportion and absolute area: proportion-only, area-only, AND or OR.
def _event_ok(p, a, thresh, min_area, rule_idx):
    p_ok = (p >= float(thresh))
    a_ok = (float(min_area) > 0.0) and (a >= float(min_area))

    # The event threshold is operational, not a direct measurement of sediment mass or geomorphic process intensity.
    if rule_idx == 0:
        return p_ok
    elif rule_idx == 1:
        return a_ok
    elif rule_idx == 2:
        return p_ok and ((float(min_area) <= 0.0) or a_ok)
    else:
        return p_ok or a_ok

# Bound area fractions to [0, 1], including defensive handling of invalid numeric values.
def _clamp01(x):
    try:
        return 0.0 if x <= 0.0 else (1.0 if x >= 1.0 else float(x))
    except Exception:
        return 0.0

# Reproject when input and PLACE grid CRSs differ; NEVER merely assign a different CRS to untransformed coordinates here.
def _ensure_same_crs(layer, target_crs, context, feedback, tag="reproj"):
    lyr = _as_layer(layer, context)
    if not lyr or not lyr.isValid():
        return lyr
    try:
        # Avoid needless reprojection; the current geometry is already expressed in the PLACE reference CRS.
        if lyr.crs() == target_crs:
            return lyr
    except Exception:
        # Avoid needless reprojection; the current geometry is already expressed in the PLACE reference CRS.
        if lyr.crs() == target_crs:
            return lyr

    if feedback:
        feedback.pushInfo(f"[CRS] Reprojecting {lyr.name()} {lyr.crs().authid()} -> {target_crs.authid()}")

    out = _run(
        "native:reprojectlayer",
        {"INPUT": lyr, "TARGET_CRS": target_crs, "OUTPUT": "TEMPORARY_OUTPUT"},
        context, feedback
    )["OUTPUT"]
    return _as_layer(out, context) or out

# Map QGIS field types into conservative SQLite storage affinities before streaming geometry-free tables.
def _sqlite_type_for_qgs_field(field):
    """Return a conservative SQLite storage class for a QgsField."""
    qtype = field.type()
    integer_types = {
        QVariant.Int, QVariant.UInt, QVariant.LongLong, QVariant.ULongLong,
        QVariant.Bool,
    }
    if qtype in integer_types:
        return "INTEGER"
    if qtype == QVariant.Double:
        return "REAL"
    if qtype == QVariant.ByteArray:
        return "BLOB"
    return "TEXT"


# Serialise PyQGIS, Python and Qt scalars into SQLite-bound values; date/time types are stored as ISO text.
def _sqlite_value(value):
    """Convert QGIS/Python values to sqlite3-compatible scalar values."""
    if value is None:
        return None
    try:
        if QgsVariantUtils.isNull(value):
            return None
    except Exception:
        pass
    if isinstance(value, QVariant):
        try:
            value = value.value()
        except Exception:
            return None
    if value is None:
        return None
    if isinstance(value, (datetime, date)):
        return value.isoformat()
    if isinstance(value, bool):
        return int(value)
    if isinstance(value, (int, float, str, bytes, bytearray)):
        return value
    # QDate/QDateTime/QTime and other Qt scalar types.
    for meth in ("toString", "toPyDateTime", "toPyDate"):
        try:
            if hasattr(value, meth):
                converted = getattr(value, meth)()
                if isinstance(converted, (datetime, date)):
                    return converted.isoformat()
                if converted is not None:
                    return str(converted)
        except Exception:
            pass
    return str(value)


# Drop an existing registered GeoPackage attribute table/view and its ancillary metadata before recreating the output table.
def _drop_gpkg_object(con, table_name):
    """Remove a table/view and its GeoPackage registrations."""
    for meta in ("gpkg_geometry_columns", "gpkg_contents", "gpkg_ogr_contents"):
        exists = con.execute(
            "SELECT 1 FROM sqlite_master WHERE type='table' AND name=?", (meta,)
        ).fetchone()
        if not exists:
            continue
        cols = [r[1] for r in con.execute(f'PRAGMA table_info("{meta}")')]
        if "table_name" in cols:
            con.execute(f'DELETE FROM "{meta}" WHERE table_name=?', (table_name,))
    obj = con.execute(
        "SELECT type FROM sqlite_master WHERE name=?", (table_name,)
    ).fetchone()
    if obj:
        quoted = '"' + str(table_name).replace('"', '""') + '"'
        if obj[0] == "view":
            con.execute(f"DROP VIEW {quoted}")
        else:
            con.execute(f"DROP TABLE {quoted}")


# Stream a large geometry-free table in bounded batches. Reopen through SQL and verify exact persisted row count and a sampled attribute tuple.
def _write_attribute_table_sqlite(layer, gpkg_path, layer_name, feedback=None, batch_size=2000):
    """Stream a no-geometry QGIS layer directly into a GeoPackage attribute table.

    QGIS/OGR can report success while writing only the schema of a very large
    in-memory no-geometry layer. This writer bypasses that failure mode and then
    verifies the persisted row count with SQLite before returning.
    """
    lyr = layer
    lname = _safe_layername(layer_name)
    fields = [QgsField(f) for f in lyr.fields() if f.name().casefold() not in {"fid", "ogc_fid"}]

    seen = set()
    for fld in fields:
        key = fld.name().casefold()
        if key in seen:
            raise QgsProcessingException(
                f"[WRITE] Layer '{lname}' contains a case-insensitive duplicate field: {fld.name()}"
            )
        seen.add(key)

    quoted_table = '"' + lname.replace('"', '""') + '"'
    col_defs = []
    col_names = []
    for fld in fields:
        nm = fld.name()
        quoted = '"' + nm.replace('"', '""') + '"'
        col_defs.append(f"{quoted} {_sqlite_type_for_qgs_field(fld)}")
        col_names.append(nm)

    # Use the GeoPackage SQLite database directly for verified, large attribute-table operations.
    con = sqlite3.connect(gpkg_path, timeout=120.0)
    written = 0
    sample_expected = None
    try:
        con.execute("PRAGMA busy_timeout=120000")
        con.execute("PRAGMA foreign_keys=OFF")
        con.execute("PRAGMA synchronous=NORMAL")
        con.execute("PRAGMA temp_store=MEMORY")
        # Obtain a write transaction before removing/recreating the destination table.
        con.execute("BEGIN IMMEDIATE")
        _drop_gpkg_object(con, lname)
        con.execute(
            f"CREATE TABLE {quoted_table} (fid INTEGER PRIMARY KEY AUTOINCREMENT NOT NULL"
            + (", " + ", ".join(col_defs) if col_defs else "")
            + ")"
        )
        now = datetime.utcnow().strftime("%Y-%m-%dT%H:%M:%S.%fZ")
        con.execute(
            "INSERT INTO gpkg_contents "
            "(table_name,data_type,identifier,description,last_change) "
            "VALUES (?,?,?,?,?)",
            (lname, "attributes", lname, f"Module 3B attribute table {lname}", now),
        )

        if col_names:
            quoted_cols = ",".join('"' + n.replace('"', '""') + '"' for n in col_names)
            placeholders = ",".join("?" for _ in col_names)
            insert_sql = f"INSERT INTO {quoted_table} ({quoted_cols}) VALUES ({placeholders})"
            batch = []
            for feat in lyr.getFeatures():
                row = tuple(_sqlite_value(feat[fld.name()]) for fld in fields)
                if sample_expected is None:
                    sample_expected = row
                batch.append(row)
                if len(batch) >= batch_size:
                    # Commit INSERT statements in bounded batches to avoid holding a million-row statement list in Python memory.
                    con.executemany(insert_sql, batch)
                    written += len(batch)
                    batch.clear()
                    if feedback and written % 100000 == 0:
                        feedback.pushInfo(f"[WRITE] {lname}: persisted {written:,} rows ...")
            if batch:
                # Commit INSERT statements in bounded batches to avoid holding a million-row statement list in Python memory.
                con.executemany(insert_sql, batch)
                written += len(batch)

        # Useful indexes for Step 3 and diagnostics.
        lower_names = {n.casefold(): n for n in col_names}
        for idx_fields in (("block_id",), ("place_id",), ("place_id", "y1", "y2")):
            if not all(n in lower_names for n in idx_fields):
                continue
            real_fields = [lower_names[n] for n in idx_fields]
            idx_name = _safe_layername("idx_" + lname + "_" + "_".join(real_fields))
            cols_sql = ",".join('"' + n.replace('"', '""') + '"' for n in real_fields)
            con.execute(f'CREATE INDEX IF NOT EXISTS "{idx_name}" ON {quoted_table} ({cols_sql})')

        if con.execute(
            "SELECT 1 FROM sqlite_master WHERE type='table' AND name='gpkg_ogr_contents'"
        ).fetchone():
            try:
                con.execute(
                    "INSERT OR REPLACE INTO gpkg_ogr_contents(table_name,feature_count) VALUES (?,?)",
                    (lname, int(written)),
                )
            except Exception:
                pass
        con.commit()

        # A QGIS success code alone does not establish that any attribute rows survived on disk.
        persisted = int(con.execute(f"SELECT COUNT(*) FROM {quoted_table}").fetchone()[0])
        if persisted != written or persisted <= 0:
            raise QgsProcessingException(
                f"[WRITE QA] {lname}: source rows written={written:,}; persisted SQL rows={persisted:,}."
            )
        if sample_expected is not None:
            got = con.execute(
                f"SELECT {','.join('"' + n.replace('"', '""') + '"' for n in col_names)} "
                f"FROM {quoted_table} ORDER BY fid LIMIT 1"
            ).fetchone()
            if got is None or tuple(got) != tuple(sample_expected):
                raise QgsProcessingException(f"[WRITE QA] {lname}: first-row attribute verification failed")
        if feedback:
            feedback.pushInfo(f"[WRITE QA] {lname}: verified {persisted:,} persisted rows")
        return persisted
    except Exception:
        try:
            con.rollback()
        except Exception:
            pass
        raise
    finally:
        con.close()


# Independent SQL check that a written GeoPackage object contains the expected positive number of rows.
def _verify_gpkg_row_count(gpkg_path, layer_name, expected=None):
    con = sqlite3.connect(gpkg_path, timeout=120.0)
    try:
        quoted = '"' + str(layer_name).replace('"', '""') + '"'
        row = con.execute(f"SELECT COUNT(*) FROM {quoted}").fetchone()
        count = int(row[0]) if row else 0
        if count <= 0:
            raise QgsProcessingException(f"[WRITE QA] Persisted table '{layer_name}' has zero rows")
        if expected is not None and int(expected) >= 0 and count != int(expected):
            raise QgsProcessingException(
                f"[WRITE QA] Persisted table '{layer_name}' has {count:,} rows; expected {int(expected):,}"
            )
        return count
    finally:
        con.close()


# Select the verified streaming SQL writer for NULL-geometry tables and the QGIS vector writer for spatial layers.
def _write_to_gpkg(layer, gpkg_path, layer_name, context, feedback):
    lyr = _as_layer(layer, context)
    if not lyr or not lyr.isValid():
        raise QgsProcessingException(f"Layer for '{layer_name}' is invalid.")

    lname = _safe_layername(layer_name)
    field_names = [f.name() for f in lyr.fields()]
    seen_casefold = {}
    duplicate_groups = []
    for nm in field_names:
        key = str(nm).casefold()
        if key in seen_casefold:
            duplicate_groups.append((seen_casefold[key], nm))
        else:
            seen_casefold[key] = nm
    if duplicate_groups:
        dup_txt = ", ".join([f"{a}/{b}" for a, b in duplicate_groups])
        raise QgsProcessingException(
            f"[WRITE] Layer '{lname}' contains case-insensitive duplicate field names: {dup_txt}"
        )

    if feedback:
        feedback.pushInfo(f"[WRITE] {lname} | in-memory fc={lyr.featureCount()}")
        feedback.pushInfo(f"[WRITE] {lname} | fields: {', '.join(field_names)}")

    # Use the direct SQLite writer for no-geometry tables. This is the critical
    # production path for PLACE_interval_long and avoids schema-only OGR writes.
    # Wide longitudinal tables are geometry-free by design: their spatial correspondence is PLACE_ID/BLOCK_ID.
    if QgsWkbTypes.geometryType(lyr.wkbType()) == QgsWkbTypes.NullGeometry:
        _write_attribute_table_sqlite(lyr, gpkg_path, lname, feedback)
        return

    drop_cols = []
    if lyr.fields().indexOf("fid") != -1:
        drop_cols.append("fid")
    if lyr.fields().indexOf("ogc_fid") != -1:
        drop_cols.append("ogc_fid")
    if drop_cols:
        out = _run(
            "native:deletecolumn",
            {"INPUT": lyr, "COLUMN": drop_cols, "OUTPUT": "TEMPORARY_OUTPUT"},
            context, feedback
        )["OUTPUT"]
        lyr = _as_layer(out, context)
        if not lyr or not lyr.isValid():
            raise QgsProcessingException(f"[WRITE] {lname} | failed after dropping columns.")

    opts = QgsVectorFileWriter.SaveVectorOptions()
    opts.driverName = "GPKG"
    opts.layerName = lname
    opts.fileEncoding = "UTF-8"
    # Overwrite only the named spatial layer, retaining other tables already present in the GeoPackage.
    opts.actionOnExistingFile = QgsVectorFileWriter.CreateOrOverwriteLayer
    transform_context = context.transformContext() if context else QgsCoordinateTransformContext()
    res = QgsVectorFileWriter.writeAsVectorFormatV3(lyr, gpkg_path, transform_context, opts)
    err = res[0] if isinstance(res, (tuple, list)) and len(res) >= 1 else res
    msg = res[1] if isinstance(res, (tuple, list)) and len(res) >= 2 else ""
    if err != QgsVectorFileWriter.NoError:
        raise QgsProcessingException(f"[WRITE] Failed writing {lname} to gpkg:\n{gpkg_path}\n{msg}")
    persisted = _verify_gpkg_row_count(gpkg_path, lname, int(lyr.featureCount()))
    if feedback:
        feedback.pushInfo(f"[WRITE QA] {lname}: verified {persisted:,} persisted rows")


