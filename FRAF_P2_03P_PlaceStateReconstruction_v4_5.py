# Normalise date-like year strings to eight-digit YYYYMMDD keys; year-only inputs are assigned 1 January by convention.
def _ymd8(val):
    s = str(val)
    # Prefer full dates, otherwise fall back to the calendar-year value with a 1 January placeholder.
    m = re.search(r"(18|19|20)\d{6}", s)
    if m:
        return m.group(0)
    m = re.search(r"(18|19|20)\d{2}[-/](\d{2})[-/](\d{2})", s)
    if m:
        return f"{m.group(1)}{m.group(2)}{m.group(3)}"
    m = re.search(r"(18|19|20)\d{2}", s)
    if m:
        return f"{m.group(0)}0101"
    return s

# Read the first populated date value in a layer. A layer is expected to represent ONE observation date, not multiple dates.
def _parse_date_field(layer, field_name, feedback=None):
    lyr = layer
    if not lyr or not lyr.isValid():
        return ("00000000", None)

    # The temporal tag comes from one field on this particular dated polygon layer.
    idx = lyr.fields().indexOf(field_name)
    if idx < 0:
        if feedback:
            feedback.reportError(f"[DATE] Field '{field_name}' not found on {lyr.name()}.")
        return ("00000000", None)

    val = None
    for f in lyr.getFeatures():
        v = f[idx]
        if v not in (None, ""):
            val = v
            break

    if val is None:
        if feedback:
            feedback.reportError(f"[DATE] No non-null values in '{field_name}' for {lyr.name()}.")
        return ("00000000", None)

    ymd = _ymd8(val)
    try:
        dt = datetime.strptime(ymd, "%Y%m%d").date()
    except Exception:
        dt = None

    return (ymd, dt)

