                if stabilise_evt == 1:
                    if stabilisation_mode == 0 and (storage_age_t2 is None or storage_age_t2 + 1e-9 < stabilisation_years):
                        qa_stabilise_early = 1
                    elif stabilisation_mode == 2 and ((storage_age_t2 is None or storage_age_t2 + 1e-9 < stabilisation_years) or p_stable + 1e-9 < stable_evidence_thresh):
                        qa_stabilise_early = 1
                    elif stabilisation_mode == 1 and ((storage_age_t2 is None or storage_age_t2 + 1e-9 < stabilisation_years) and p_stable + 1e-9 < stable_evidence_thresh):
                        qa_stabilise_early = 1
                qa_initial_stable_no_evidence = 1 if (ii == 0 and onto_state_t1 == "STABILISED_FLOODPLAIN" and
                    p_bg + 1e-9 < bg_state_thresh and p_stable + 1e-9 < stable_evidence_thresh) else 0
                # Storage recovery after an unresolved boundary observation is valid when
                # a suspended storage clock is present. Flag only storage that has neither
                # recognised T1 history, deposition evidence nor a latent storage history.
                qa_storage_without_history = 1 if (onto_state_t2 == "DEPOSITIONAL_STORAGE" and
                    onto_state_t1 not in {"ACTIVE_DOMAIN", "DEPOSITIONAL_STORAGE", "STABILISED_FLOODPLAIN"} and
                    latent_state_t1 != "ACTIVE_DOMAIN" and
                    d_evt_raw == 0 and storage_age_t1 is None) else 0
                qa_bg_active_overlap = 1 if (p_bg >= bg_state_thresh and max(pC1, pC2) >= active_contact_thresh) else 0
                qa_process_domain_mismatch = 1 if (e_evt_raw == 1 and max(pC1, pC2) < active_contact_thresh) else 0
                qa_unresolved = 1 if (onto_state_t1 == "UNRESOLVED" or onto_state_t2 == "UNRESOLVED") else 0
                qa_mixed = 1 if (mixed_t1 or mixed_t2) else 0
                qa_clock = 0
                # Unresolved endpoints may carry a suspended storage clock; other
                # non-storage states must not. Age and start date must travel together.
                if ((onto_state_t1 not in {"DEPOSITIONAL_STORAGE", "UNRESOLVED"} and (storage_age_t1 is not None or storage_start_t1)) or
                    (onto_state_t2 not in {"DEPOSITIONAL_STORAGE", "STABILISED_FLOODPLAIN", "UNRESOLVED"} and (storage_age_t2 is not None or storage_start_t2)) or
                    ((storage_age_t1 is None) != (not bool(storage_start_t1))) or
                    ((storage_age_t2 is None) != (not bool(storage_start_t2))) or
                    (storage_age_t1 is not None and storage_age_t1 < -1e-9) or
                    (storage_age_t2 is not None and storage_age_t2 < -1e-9)):
                    qa_clock = 1
                if onto_state_t2 == "DEPOSITIONAL_STORAGE" and storage_clock_reset_t2 == 1:
                    if storage_age_t2 is None or abs(storage_age_t2) > 1e-9 or str(storage_start_t2 or "") != str(y2):
                        qa_clock = 1
                if (onto_state_t1 == "DEPOSITIONAL_STORAGE" and onto_state_t2 == "DEPOSITIONAL_STORAGE" and
                    storage_clock_reset_t2 == 0 and storage_age_t1 is not None and storage_age_t2 is not None and
                    abs(storage_age_t2 - (storage_age_t1 + interval_years)) > 1e-6):
                    qa_clock = 1
                if onto_state_t2 == "UNRESOLVED" and storage_age_t1 is not None:
                    if storage_age_t2 != storage_age_t1 or storage_start_t2 != storage_start_t1:
                        qa_clock = 1
                qa_fraction_sum = 1 if (abs(state_sum_t1 - 1.0) > 1e-6 or abs(state_sum_t2 - 1.0) > 1e-6) else 0
                source_t2_upper = str(state_source_t2 or "").upper()
                qa_source = 1 if (
                    (onto_state_t2 == "ACTIVE_DOMAIN" and source_t2_upper != "DATED_ACTIVE_DOMAIN") or
                    (onto_state_t2 == "STABILISED_FLOODPLAIN" and source_t2_upper in {"ACTIVE_EXIT_UNCONFIRMED_STORAGE", "ACTIVE_EXIT_DEPOSITION_CONFIRMED"}) or
                    (onto_state_t2 == "DEPOSITIONAL_STORAGE" and source_t2_upper == "STORAGE_STABILISATION_RULE")
                ) else 0

                qa_latent = 0
                # Extend or start an ambiguity run and remember the most recent defensible ontological state.
                if boundary_mixed_t2:
                    expected_latent_t2 = (
                        onto_state_t1 if onto_state_t1 in VALID_STATES
                        else (latent_state_t1 if latent_state_t1 in VALID_STATES else None)
                    )
                    if latent_state_t2 != expected_latent_t2:
                        qa_latent = 1
                    if ambiguity_run_id_t2 <= 0 or ambiguity_run_length_t2 <= 0:
                        qa_latent = 1
                if ambiguity_resolved:
                    if row_ambiguity_run_id <= 0 or row_ambiguity_run_length <= 0:
                        qa_latent = 1
                    if bridged_origin_state is not None and bridged_origin_state != latent_state_t1:
                        qa_latent = 1
                if bridged_any and not ambiguity_resolved:
                    qa_latent = 1
                qa_bridged_invalid = 1 if bridged_invalid else 0

                chain_ok = 1
                if prev_onto_state is not None and onto_state_t1 != prev_onto_state:
                    chain_ok = 0

                fatal_flags = []
                warning_flags = []
                flag_pairs = [
                    (qa_active_below, "ACTIVE_STATE_BELOW_THRESHOLD", True),
                    (qa_nonactive_above, "NONACTIVE_STATE_ABOVE_THRESHOLD", True),
                    (qa_active_to_stable, "DIRECT_ACTIVE_TO_STABLE", True),
                    (qa_stabilise_early, "STABILISATION_BEFORE_RULE", True),
                    (qa_initial_stable_no_evidence, "INITIAL_STABLE_WITHOUT_EVIDENCE", True),
                    (qa_storage_without_history, "STORAGE_WITHOUT_HISTORY_OR_DEPOSITION", True),
                    (qa_clock, "STORAGE_CLOCK_INCONSISTENT", True),
                    (qa_source, "STATE_SOURCE_INCONSISTENT", True),
                    (qa_fraction_sum, "STATE_FRACTION_SUM_FAILURE", True),
                    (qa_latent, "LATENT_STATE_INCONSISTENT", True),
                    (qa_bridged_invalid, "INVALID_BRIDGED_TRANSITION", True),
                    (0 if chain_ok else 1, "STATE_CHAIN_FAILURE", True),
                    (qa_bg_active_overlap, "BACKGROUND_ACTIVE_OVERLAP", False),
                    (qa_process_domain_mismatch, "EROSION_WITHOUT_ACTIVE_ENDPOINT_CONTACT", False),
                    (qa_unresolved, "UNRESOLVED_ENDPOINT", False),
                    (qa_mixed, "MIXED_ACTIVE_CONTACT", False),
                ]
                for is_set, label, is_fatal in flag_pairs:
                    if is_set:
                        (fatal_flags if is_fatal else warning_flags).append(label)
                anomaly_flags = fatal_flags + warning_flags
                anomaly_severity = "FATAL" if fatal_flags else ("WARNING" if warning_flags else "NONE")

                prev_onto_state = onto_state_t2
                prev_latent_state = latent_state_t2
                prev_ambiguity_run_id = ambiguity_run_id_t2
