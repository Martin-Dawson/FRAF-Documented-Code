                # occupancy, provenance and elapsed-time evidence rather than merely
                # comparing outputs generated by the same state function.
                # QA checks detect violations of observational support thresholds and storage/provenance semantics.
                qa_active_below = 1 if ((onto_state_t1 == "ACTIVE_DOMAIN" and pC1 + 1e-9 < c_thresh) or
                                        (onto_state_t2 == "ACTIVE_DOMAIN" and pC2 + 1e-9 < c_thresh)) else 0
