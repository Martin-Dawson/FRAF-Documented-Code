# Batch-add absent attributes via the provider. Existing fields are intentionally left intact so repeated setup does not reorder or overwrite their values.
def _ensure_fields_fast(layer, field_specs):
    """
    field_specs: list of (name, QVariant.Type, length, precision)
    """
    # Provider updates are faster than repeatedly calling fieldcalculator across hundreds of thousands of PLACEs.
    pr = layer.dataProvider()
    existing = {f.name() for f in layer.fields()}
    new_fields = []
    for (name, qtype, flen, fprec) in field_specs:
        if name not in existing:
            fld = QgsField(name, qtype)
            if flen is not None:
                fld.setLength(int(flen))
            if fprec is not None:
                fld.setPrecision(int(fprec))
            new_fields.append(fld)
    # A non-empty missing-field list is the only reason to modify the schema.
    if new_fields:
        pr.addAttributes(new_fields)
        layer.updateFields()
# Normalise a bare .gpkg output target to a QGIS layer URI without changing targets already qualified by |layername=.
def _ensure_gpkg_layername(dest: str, layername: str) -> str:
    """
    If a destination is a .gpkg path without '|layername=', add one.
    """
    if not dest:
        return dest
    s = str(dest)
    if s.lower().endswith(".gpkg") and "|layername=" not in s.lower():
        return f"{s}|layername={layername}"
    return s

# Apply pre-indexed attribute edits in one provider request; failure must be fatal because partial PLACE fields would invalidate later event tables.
def _bulk_update(layer, changes, feedback=None):
    """
    changes: { fid: { fieldIndex: value, ... }, ... }
    """
    pr = layer.dataProvider()
    ok = pr.changeAttributeValues(changes)
    if not ok:
        raise QgsProcessingException("changeAttributeValues() returned False.")
    layer.updateFields()
    layer.triggerRepaint()
# Convert PyQGIS/Qt null and variant types to a Python float with a defined fallback, avoiding NULL propagation into area and proportion arithmetic.
def _to_float(v, default=0.0):
    if v is None:
        return default

    try:
        if QgsVariantUtils.isNull(v):
            return default
    except Exception:
        pass

    # Qt values are unwrapped explicitly because QVariant float conversion differs from native Python conversion.
    if isinstance(v, QVariant):
        try:
            ok, d = v.toDouble()
            return d if ok else default
        except Exception:
            try:
                return float(v.value())
            except Exception:
                return default

    try:
        return float(v)
    except Exception:
        s = str(v).strip()
        return float(s) if s else default

# Convert QGIS attribute values to integer IDs or flags, including numeric-looking doubles; use the supplied fallback for invalid/missing values.
def _to_int(v, default=None):
    if v is None:
        return default
    try:
        if QgsVariantUtils.isNull(v):
            return default
    except Exception:
        pass
    try:
        return int(v)
    except Exception:
        try:
            return int(round(float(v)))
        except Exception:
            return default


# Feature-detect optional QGIS algorithms before selecting version-dependent geometry or point-generation fallbacks.
def _algo_exists(alg_id):
    from qgis.core import QgsApplication
    try:
        return QgsApplication.processingRegistry().algorithmById(alg_id) is not None
    except Exception:
        return False

# Central QGIS Processing invocation. Algorithms are child operations sharing the parent processing context.
def _run(alg, params, context, feedback=None):
    if feedback:
        feedback.pushInfo(f"Running {alg} ...")
    return processing.run(alg, params, context=context, is_child_algorithm=True)

# Resolve a file, URI, layer name, Processing output or existing object to a valid QgsVectorLayer; no geometry/attribute transformation is performed.
def _as_layer(obj, context):
    try:
        if hasattr(obj, "isValid") and obj.isValid():
            return obj
    except Exception:
        pass

    try:
        lyr = QgsProcessingUtils.mapLayerFromString(str(obj), context)
        if lyr and lyr.isValid():
            return lyr
    except Exception:
        pass

    try:
        lyr = QgsProject.instance().mapLayer(str(obj))
        if lyr and lyr.isValid():
            return lyr
    except Exception:
        pass

    if isinstance(obj, str) and os.path.exists(obj):
        lyr = QgsVectorLayer(obj, os.path.basename(obj), "ogr")
        if lyr.isValid():
            return lyr

    return None

