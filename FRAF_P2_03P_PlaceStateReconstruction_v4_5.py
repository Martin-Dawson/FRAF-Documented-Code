# Remove a provider-layer suffix from a file-backed source URI before inspecting filesystem metadata.
def _normalise_source_path(source_text):
    s = str(source_text or "")
    return s.split("|", 1)[0].strip()

# Capture source path, provider, row count, extent, CRS and filesystem metadata for overlap-cache reproducibility checks.
def _layer_fingerprint(layer):
    lyr = layer
    if not lyr or not lyr.isValid():
        return {"valid": False}
    # Source fingerprints are metadata-based rather than full file hashes, to avoid expensive reads of large input GeoPackages.
    src = str(lyr.source() or "")
    base = _normalise_source_path(src)
    file_size = None
    file_mtime_ns = None
    try:
        if base and os.path.exists(base):
            st = os.stat(base)
            file_size = int(st.st_size)
            file_mtime_ns = int(st.st_mtime_ns)
    except Exception:
        pass
    try:
        ext = lyr.extent()
        extent = [round(float(ext.xMinimum()), 6), round(float(ext.yMinimum()), 6),
                  round(float(ext.xMaximum()), 6), round(float(ext.yMaximum()), 6)]
    except Exception:
        extent = None
    try:
        crs = lyr.crs().authid()
    except Exception:
        crs = ""
    try:
        count = int(lyr.featureCount())
    except Exception:
        count = -1
    return {
        "valid": True,
        "name": str(lyr.name()),
        "source": src,
        "provider": str(lyr.providerType()),
        "feature_count": count,
        "crs": crs,
        "extent": extent,
        "file_size": file_size,
        "file_mtime_ns": file_mtime_ns,
    }

# Produce canonical JSON and a SHA-256 signature so equivalent cache configurations have the same key.
def _stable_json_hash(value):
    txt = json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=True)
    return hashlib.sha256(txt.encode("utf-8")).hexdigest(), txt

# Resumable disk-backed cache. Signature validation prevents mixing PLACE geometry and EA overlays from incompatible runs.
class _OverlapCache:
    """Small resumable SQLite cache for non-zero PLACE overlap values.

    The cache is deliberately separate from the final GeoPackage. A completed
    overlay is recorded even when it has zero matches, so interrupted runs can
    resume without repeating finished geometry work.
    """
    # Initialise SQLite overlap-cache schema, verify input signature, and move an incompatible existing cache out of the active path.
    def __init__(self, path, signature_hash, signature_json, reuse=True, reset=False, feedback=None):
        self.path = os.path.normpath(path)
        self.feedback = feedback
        os.makedirs(os.path.dirname(self.path), exist_ok=True)
        if reset or not reuse:
            self._remove_existing()
        self.conn = sqlite3.connect(self.path, timeout=120.0)
        self.conn.execute("PRAGMA journal_mode=DELETE")
        self.conn.execute("PRAGMA synchronous=NORMAL")
        self.conn.execute("PRAGMA temp_store=MEMORY")
        self.conn.executescript("""
            CREATE TABLE IF NOT EXISTS metadata (
                key TEXT PRIMARY KEY,
                value TEXT NOT NULL
            );
            CREATE TABLE IF NOT EXISTS completed (
                stage TEXT NOT NULL,
                overlay_key TEXT NOT NULL,
                nonzero_rows INTEGER NOT NULL,
                completed_utc TEXT NOT NULL,
                PRIMARY KEY(stage, overlay_key)
            );
            CREATE TABLE IF NOT EXISTS overlap_value (
                stage TEXT NOT NULL,
                overlay_key TEXT NOT NULL,
                block_id INTEGER NOT NULL,
                area_equiv REAL NOT NULL,
                proportion REAL NOT NULL,
                PRIMARY KEY(stage, overlay_key, block_id)
            );
            CREATE INDEX IF NOT EXISTS idx_overlap_stage_key
                ON overlap_value(stage, overlay_key);
        """)
        self.conn.commit()
        # Do not silently reuse overlap values obtained from a different envelope, dates, thresholds or overlay set.
        old = self._meta_get("signature_hash")
        # Archive stale cache content instead of appending incompatible overlap rows to it.
        if old and old != signature_hash:
            self.conn.close()
            stamp = datetime.utcnow().strftime("%Y%m%dT%H%M%SZ")
            stale = self.path + f".stale_{stamp}"
            try:
                os.replace(self.path, stale)
                if feedback:
                    feedback.pushWarning(
                        f"[CACHE] Existing overlap cache does not match current inputs; moved to {stale}"
                    )
            except Exception:
                try:
                    os.remove(self.path)
                except Exception:
                    pass
            self.conn = sqlite3.connect(self.path, timeout=120.0)
            self.conn.execute("PRAGMA journal_mode=DELETE")
            self.conn.execute("PRAGMA synchronous=NORMAL")
            self.conn.execute("PRAGMA temp_store=MEMORY")
            self.conn.executescript("""
                CREATE TABLE metadata (key TEXT PRIMARY KEY, value TEXT NOT NULL);
                CREATE TABLE completed (stage TEXT NOT NULL, overlay_key TEXT NOT NULL, nonzero_rows INTEGER NOT NULL, completed_utc TEXT NOT NULL, PRIMARY KEY(stage, overlay_key));
                CREATE TABLE overlap_value (stage TEXT NOT NULL, overlay_key TEXT NOT NULL, block_id INTEGER NOT NULL, area_equiv REAL NOT NULL, proportion REAL NOT NULL, PRIMARY KEY(stage, overlay_key, block_id));
                CREATE INDEX idx_overlap_stage_key ON overlap_value(stage, overlay_key);
            """)
        self._meta_set("signature_hash", signature_hash)
        self._meta_set("signature_json", signature_json)
        self._meta_set("engine_schema", "M3B_OVERLAP_CACHE_V2_INDEXED_EXACT")
        self.conn.commit()

    # Delete an explicitly reset cache and any SQLite journal sidecars.
    def _remove_existing(self):
        for suffix in ("", "-journal", "-wal", "-shm"):
            p = self.path + suffix
            try:
                if os.path.exists(p):
                    os.remove(p)
            except Exception as exc:
                raise QgsProcessingException(f"Could not reset overlap cache {p}: {exc}")

    # Read one cache metadata setting by key.
    def _meta_get(self, key):
        row = self.conn.execute("SELECT value FROM metadata WHERE key=?", (str(key),)).fetchone()
        return row[0] if row else None

    # Insert or replace one cache metadata setting by key.
    def _meta_set(self, key, value):
        self.conn.execute(
            "INSERT INTO metadata(key,value) VALUES(?,?) ON CONFLICT(key) DO UPDATE SET value=excluded.value",
            (str(key), str(value)),
        )

    # Distinguish a completed zero-overlap overlay from an overlay not yet processed.
    def has(self, stage, overlay_key):
        row = self.conn.execute(
            "SELECT 1 FROM completed WHERE stage=? AND overlay_key=?",
            (str(stage), str(overlay_key)),
        ).fetchone()
        return bool(row)

    # Count completed per-overlay checkpoints available for reuse.
    def completed_count(self):
        return int(self.conn.execute("SELECT COUNT(*) FROM completed").fetchone()[0])

    # Commit one overlay atomically, including zero matches, and record its completion time.
    def save(self, stage, overlay_key, values):
        stage = str(stage); overlay_key = str(overlay_key)
        # Each overlay is one atomic checkpoint. Interrupted later overlays cannot corrupt a previously completed checkpoint.
        self.conn.execute("BEGIN")
        try:
            self.conn.execute(
                "DELETE FROM overlap_value WHERE stage=? AND overlay_key=?",
                (stage, overlay_key),
            )
            rows = []
            for block_id, pair in (values or {}).items():
                area, prop = pair
                prop = _clamp01(prop)
                area = max(0.0, float(area or 0.0))
                # Store only positive PLACE intersections; missing rows can be reconstructed as zero overlap.
                if area <= 0.0 and prop <= 0.0:
                    continue
                rows.append((stage, overlay_key, int(block_id), area, prop))
            if rows:
                for i in range(0, len(rows), 50000):
                    self.conn.executemany(
                        "INSERT OR REPLACE INTO overlap_value(stage,overlay_key,block_id,area_equiv,proportion) VALUES(?,?,?,?,?)",
                        rows[i:i+50000],
                    )
            self.conn.execute(
                "INSERT OR REPLACE INTO completed(stage,overlay_key,nonzero_rows,completed_utc) VALUES(?,?,?,?)",
                (stage, overlay_key, len(rows), datetime.utcnow().isoformat(timespec="seconds") + "Z"),
            )
            self.conn.commit()
        except Exception:
            self.conn.rollback()
            raise

    # Restore saved nonzero overlaps as a PLACE-ID keyed {area, fraction} dictionary.
    def load(self, stage, overlay_key):
        rows = self.conn.execute(
            "SELECT block_id,area_equiv,proportion FROM overlap_value WHERE stage=? AND overlay_key=?",
            (str(stage), str(overlay_key)),
        ).fetchall()
        return {int(b): (float(a), float(p)) for b, a, p in rows}

    # List checkpoint status records for the audit CSV.
    def status_rows(self):
        return self.conn.execute(
            "SELECT stage,overlay_key,nonzero_rows,completed_utc FROM completed ORDER BY stage,overlay_key"
        ).fetchall()

    # Commit and close the SQLite connection; must be called once overlap extraction is complete.
    def close(self):
        try:
            self.conn.commit()
        finally:
            self.conn.close()

# Resolve output field names case-insensitively to handle different QGIS/provider capitalisation.
def _casefold_field_name(layer, requested):
    req = str(requested).casefold()
    for fld in layer.fields():
        if fld.name().casefold() == req:
            return fld.name()
    return None

# Return a descriptively named, CRS-matched layer clone for QGIS multi-layer overlap diagnostics.
def _named_overlay_clone(layer, key, target_crs, context, feedback):
    lyr = _as_layer(layer, context)
    if not lyr or not lyr.isValid():
        return None
    if lyr.crs() != target_crs:
        lyr = _ensure_same_crs(lyr, target_crs, context, feedback, tag=f"overlay_{key}")
    try:
        clone = lyr.clone()
    except Exception:
        clone = lyr
    clone.setName(str(key))
    return clone

# Convert the legacy materialised-intersection area totals to per-PLACE [area, fraction] values.
def _legacy_spec_values(blocks, block_areas, spec, context, feedback):
    sums = _channel_area_by_block(
        blocks, spec["layer"], context, feedback,
        do_fix=bool(spec.get("fix_legacy", False)),
        do_dissolve=bool(spec.get("dissolve_legacy", False)),
        tag=f"{spec['stage']} {spec['key']}",
    )
    out = {}
    for pid, raw_area in sums.items():
        ab = float(block_areas.get(int(pid), 0.0) or 0.0)
        p = _clamp01(float(raw_area or 0.0) / ab) if ab > 0 else 0.0
        area = ab * p
        if area > 0 or p > 0:
            out[int(pid)] = (area, p)
    return out


_M3B_BLOCK_INDEX_CACHE = {}

# Define an in-process reuse key for the fixed-place geometry index; note this is not a content hash.
def _block_index_cache_key(blocks):
    try:
        src = str(blocks.source())
    except Exception:
        src = str(id(blocks))
    try:
        ext = blocks.extent()
        ext_key = (round(ext.xMinimum(), 3), round(ext.xMaximum(), 3), round(ext.yMinimum(), 3), round(ext.yMaximum(), 3))
    except Exception:
        ext_key = ()
    return (src, int(blocks.featureCount()), ext_key)

# Construct a reusable R-tree plus immutable copies of PLACE geometries and a feature-ID-to-PLACE-ID lookup.
# The cache is shared by all observation dates and EA classes within this Python run.
def _get_block_spatial_cache(blocks, feedback=None):
    """Build once per run: spatial index + immutable PLACE geometries keyed by feature id."""
    key = _block_index_cache_key(blocks)
    cached = _M3B_BLOCK_INDEX_CACHE.get(key)
    if cached is not None:
        return cached

    t0 = time.time()
    # The R-tree reduces candidate tests before exact GEOS geometry intersections are evaluated.
    index = QgsSpatialIndex()
    fid_to_pid = {}
    geom_by_fid = {}
    bid_field = _pick_block_id_field(blocks)
    if not bid_field:
        raise QgsProcessingException("Could not build PLACE spatial index: BLOCK_ID field not found.")
    n = 0
    for feat in blocks.getFeatures():
        pid = _to_int(feat[bid_field], None)
        geom = feat.geometry()
        if pid is None or geom is None or geom.isEmpty():
            continue
        index.addFeature(feat)
        fid = int(feat.id())
        fid_to_pid[fid] = int(pid)
        # Keep immutable geometry copies, because features from a provider iterator may not remain valid.
        geom_by_fid[fid] = QgsGeometry(geom)
        n += 1
        if feedback and n % 10000 == 0:
            feedback.pushInfo(f"[INDEX] Cached {n:,} PLACE geometries ...")
        if feedback and feedback.isCanceled():
            raise QgsProcessingException("Processing cancelled while building PLACE spatial index.")
    if n == 0:
        raise QgsProcessingException("Could not build PLACE spatial index: no valid BLOCK_ID geometries.")
    cached = {"index": index, "fid_to_pid": fid_to_pid, "geom_by_fid": geom_by_fid}
    _M3B_BLOCK_INDEX_CACHE[key] = cached
    if feedback:
        feedback.pushInfo(f"[INDEX] PLACE spatial index ready: {n:,} geometries in {(time.time()-t0)/60.0:.2f} min.")
    return cached

# Copy and make valid a geometry when needed, without mutating the provider source feature.
def _safe_valid_geometry(geom):
    if geom is None or geom.isEmpty():
        return None
    g = QgsGeometry(geom)
    try:
        if not g.isGeosValid():
            fixed = g.makeValid()
            if fixed is not None and not fixed.isEmpty():
                g = fixed
    except Exception:
        pass
    return g if g is not None and not g.isEmpty() else None

# Primary exact overlap engine: spatial-index bbox filtering followed by true GEOS intersection areas per PLACE.
def _indexed_spec_values(blocks, block_areas, spec, context, feedback, spatial_cache=None):
    """Exact overlap area using a reusable PLACE spatial index.

    No split intersection layer is materialised. Each overlay feature queries only
    candidate PLACE cells by bounding box. Exact intersections are accumulated by
    BLOCK_ID and the result is checkpointed immediately by the caller.
    """
    t0 = time.time()
    layer = _as_layer(spec.get("layer"), context)
    if not layer or not layer.isValid() or layer.featureCount() == 0:
        return {}
    if layer.crs() != blocks.crs():
        layer = _ensure_same_crs(layer, blocks.crs(), context, feedback, tag=f"indexed_{spec['key']}")
    spatial_cache = spatial_cache or _get_block_spatial_cache(blocks, feedback)
    index = spatial_cache["index"]
    fid_to_pid = spatial_cache["fid_to_pid"]
    geom_by_fid = spatial_cache["geom_by_fid"]

    overlay_geoms = []
    # Read overlay features once; invalid/empty geometries cannot contribute to intersection area.
    for feat in layer.getFeatures():
        g = _safe_valid_geometry(feat.geometry())
        if g is not None:
            overlay_geoms.append(g)
    if not overlay_geoms:
        return {}

    # Only overlays explicitly marked for dissolve are unioned. Annual Active
    # Domain and EA class layers are expected to be planar/non-overlapping; their
    # exact block intersections are summed and finally bounded by A_block.
    # Only a semantically required footprint union should be dissolved; yearly EA and AD layers normally remain undissolved.
    if bool(spec.get("dissolve_legacy", False)) and len(overlay_geoms) > 1:
        if feedback:
            feedback.pushInfo(f"[INDEXED] {spec['stage']}:{spec['key']} unary-union of {len(overlay_geoms):,} overlay geometries ...")
        try:
            ug = QgsGeometry.unaryUnion(overlay_geoms)
            overlay_geoms = [ug] if ug is not None and not ug.isEmpty() else overlay_geoms
        except Exception as exc:
            if feedback:
                feedback.pushWarning(f"[INDEXED] Unary union failed for {spec['stage']}:{spec['key']}; processing features separately: {exc}")

    raw_by_pid = defaultdict(float)
    candidate_tests = 0
    exact_intersections = 0
    last_log = time.time()
    for gi, og in enumerate(overlay_geoms, start=1):
        # Bounding-box hits are ONLY possible intersections; each candidate still requires an exact geometry predicate.
        cand_fids = index.intersects(og.boundingBox())
        for fid in cand_fids:
            bg = geom_by_fid.get(int(fid))
            pid = fid_to_pid.get(int(fid))
            if bg is None or pid is None:
                continue
            candidate_tests += 1
            try:
                if not og.intersects(bg):
                    continue
                # A full-contained PLACE can use its known area without constructing an expensive overlay geometry.
                if og.contains(bg):
                    a = float(block_areas.get(int(pid), 0.0) or 0.0)
                else:
                    # Partial overlap uses true polygon intersection area rather than raster or point approximations.
                    inter = bg.intersection(og)
                    if inter is None or inter.isEmpty():
                        continue
                    a = float(inter.area())
                if a > 0.0:
                    raw_by_pid[int(pid)] += a
                    exact_intersections += 1
            except Exception:
                # Retry with valid copies for rare GEOS topology edge cases.
                try:
                    bg2 = _safe_valid_geometry(bg)
                    og2 = _safe_valid_geometry(og)
                    if bg2 is None or og2 is None or not og2.intersects(bg2):
                        continue
                    inter = bg2.intersection(og2)
                    if inter is not None and not inter.isEmpty():
                        a = float(inter.area())
                        if a > 0.0:
                            raw_by_pid[int(pid)] += a
                            exact_intersections += 1
                except Exception:
                    continue

            now = time.time()
            if feedback and (candidate_tests % 5000 == 0 or now - last_log >= 60.0):
                feedback.pushInfo(
                    f"[INDEXED] {spec['stage']}:{spec['key']} overlay {gi}/{len(overlay_geoms)}; "
                    f"candidate tests={candidate_tests:,}; positive intersections={exact_intersections:,}; "
                    f"elapsed={(now-t0)/60.0:.2f} min"
                )
                last_log = now
            if feedback and feedback.isCanceled():
                raise QgsProcessingException(f"Processing cancelled during indexed overlap {spec['stage']}:{spec['key']}.")

    out = {}
    overfull = 0
    for pid, raw_area in raw_by_pid.items():
        ab = float(block_areas.get(int(pid), 0.0) or 0.0)
        if ab <= 0.0:
            continue
        # Record possible overlay double-counting before proportions are capped to physical PLACE area.
        if raw_area > ab * 1.01:
            overfull += 1
        p = _clamp01(raw_area / ab)
        area_equiv = ab * p
        if area_equiv > 0.0:
            out[int(pid)] = (area_equiv, p)
    if feedback:
        msg = (
            f"[INDEXED COMPLETE] {spec['stage']}:{spec['key']}; overlays={len(overlay_geoms):,}; "
            f"candidate tests={candidate_tests:,}; positive blocks={len(out):,}; "
            f"elapsed={(time.time()-t0)/60.0:.2f} min"
        )
        if overfull:
            msg += f"; capped overlapping-feature sums in {overfull:,} block(s)"
        feedback.pushInfo(msg)
    return out

# Dispatch overlap specs, respect completed checkpoints, and commit each completed overlay before continuing.
def _ensure_overlap_specs_cached(blocks, block_areas, specs, cache, engine_idx, batch_size, context, feedback, allow_legacy_fallback=False):
    """Ensure every overlap specification has a committed cache record.

    engine_idx 0 uses exact indexed per-overlay intersections and commits after
    every overlay. Engine 1 retains QGIS native multi-layer overlap batches for
    diagnostic comparison. Engine 2 retains materialised legacy intersections.
    """
    # Only unchecked overlays consume GIS processing time on a resumed run.
    missing = [sp for sp in specs if not cache.has(sp["stage"], sp["key"])]
    hits = len(specs) - len(missing)
    if hits and feedback:
        feedback.pushInfo(f"[CACHE] Reusing {hits}/{len(specs)} completed overlap(s).")
    if not missing:
        return

    # Empty overlays are valid completed zero-overlap results.
    valid_missing = []
    for sp in missing:
        lyr = _as_layer(sp.get("layer"), context)
        if not lyr or not lyr.isValid():
            if sp.get("required", False):
                raise QgsProcessingException(f"Required overlap layer is invalid: {sp['stage']}:{sp['key']}")
            cache.save(sp["stage"], sp["key"], {})
            continue
        # A valid empty overlay is a completed zero-overlap condition, not a processing failure.
        if lyr.featureCount() == 0:
            cache.save(sp["stage"], sp["key"], {})
            if feedback:
                feedback.pushInfo(f"[CACHE] {sp['stage']}:{sp['key']} is empty; stored zero-overlap checkpoint.")
            continue
        sp = dict(sp); sp["layer"] = lyr
        valid_missing.append(sp)

    # Production engine: exact individual overlays with immediate SQLite checkpoint writes.
    if engine_idx == 0:
        spatial_cache = _get_block_spatial_cache(blocks, feedback)
        for i, sp in enumerate(valid_missing, start=1):
            if feedback:
                feedback.pushInfo(
                    f"[OVERLAP INDEXED] {sp['stage']}:{sp['key']} ({i}/{len(valid_missing)}); "
                    "checkpoint will be committed immediately on completion."
                )
            try:
                vals = _indexed_spec_values(blocks, block_areas, sp, context, feedback, spatial_cache)
                cache.save(sp["stage"], sp["key"], vals)
                if feedback:
                    feedback.pushInfo(f"[CACHE COMMIT] {sp['stage']}:{sp['key']} rows={len(vals):,}")
            except Exception as exc:
                if feedback and feedback.isCanceled():
                    raise
                if not allow_legacy_fallback:
                    raise QgsProcessingException(
                        f"Indexed overlap failed for {sp['stage']}:{sp['key']}: {exc}. "
                        "All previously completed overlays remain cached."
                    )
                if feedback:
                    feedback.pushWarning(
                        f"[OVERLAP INDEXED] Failed for {sp['stage']}:{sp['key']} ({exc}); "
                        "using slow legacy intersection for this overlay only."
                    )
                vals = _legacy_spec_values(blocks, block_areas, dict(sp, fix_legacy=True), context, feedback)
                cache.save(sp["stage"], sp["key"], vals)
        return

    # Slow materialised-intersection path is retained for fallbacks and sensitivity checks.
    if engine_idx == 2 or not _algo_exists("native:calculatevectoroverlaps"):
        if engine_idx == 1 and feedback and not _algo_exists("native:calculatevectoroverlaps"):
            feedback.pushWarning("[OVERLAP] native:calculatevectoroverlaps unavailable; using cached legacy intersections.")
        for i, sp in enumerate(valid_missing, start=1):
            if feedback:
                feedback.pushInfo(f"[OVERLAP LEGACY] {sp['stage']}:{sp['key']} ({i}/{len(valid_missing)})")
            vals = _legacy_spec_values(blocks, block_areas, sp, context, feedback)
            cache.save(sp["stage"], sp["key"], vals)
        return

    batch_size = max(1, int(batch_size))
    total_batches = (len(valid_missing) + batch_size - 1) // batch_size
    target_crs = blocks.crs()
    # Alternative QGIS batched engine is diagnostic; it may use more memory than the indexed engine.
    for bi in range(total_batches):
        batch = valid_missing[bi * batch_size:(bi + 1) * batch_size]
        keys = [f"{sp['stage']}:{sp['key']}" for sp in batch]
        if feedback:
            feedback.pushInfo(
                f"[OVERLAP BATCH] {bi+1}/{total_batches}; overlays={len(batch)}; "
                + ", ".join(keys)
            )
        named_layers = []
        usable_specs = []
        for sp in batch:
            lyr = _named_overlay_clone(sp["layer"], sp["key"], target_crs, context, feedback)
            if not lyr or not lyr.isValid():
                if sp.get("required", False):
                    raise QgsProcessingException(f"Could not prepare required overlay {sp['stage']}:{sp['key']}")
                cache.save(sp["stage"], sp["key"], {})
                continue
            named_layers.append(lyr)
            usable_specs.append(sp)
        if not usable_specs:
            continue

        t0 = time.time()
        try:
            result = _run(
                "native:calculatevectoroverlaps",
                {"INPUT": blocks, "LAYERS": named_layers, "OUTPUT": "TEMPORARY_OUTPUT"},
                context, feedback,
            )["OUTPUT"]
            result = _as_layer(result, context)
            if not result or not result.isValid():
                raise QgsProcessingException("Batched overlap output is invalid.")
            bid_field = _pick_block_id_field(result)
            if not bid_field:
                raise QgsProcessingException("Batched overlap output has no BLOCK_ID field.")
            field_map = {}
            for sp in usable_specs:
                pc_name = _casefold_field_name(result, f"{sp['key']}_pc")
                area_name = _casefold_field_name(result, f"{sp['key']}_area")
                if not pc_name or not area_name:
                    raise QgsProcessingException(
                        f"Overlap output fields missing for {sp['key']}; expected {sp['key']}_area and {sp['key']}_pc."
                    )
                field_map[sp["key"]] = (area_name, pc_name)
            values = {sp["key"]: {} for sp in usable_specs}
            rows_seen = 0
            for feat in result.getFeatures():
                pid = _to_int(feat[bid_field], None)
                if pid is None:
                    continue
                rows_seen += 1
                ab = float(block_areas.get(pid, 0.0) or 0.0)
                for sp in usable_specs:
                    _area_name, pc_name = field_map[sp["key"]]
                    pct = _to_float(feat[pc_name], 0.0)
                    p = _clamp01(pct / 100.0)
                    area_equiv = ab * p
                    if area_equiv > 0.0 or p > 0.0:
                        values[sp["key"]][pid] = (area_equiv, p)
            # A batch with dropped PLACE records cannot be accepted as a valid cached overlay.
            if rows_seen != len(block_areas):
                raise QgsProcessingException(
                    f"Batched overlap row mismatch: output={rows_seen:,}; expected PLACE rows={len(block_areas):,}."
                )
            for sp in usable_specs:
                cache.save(sp["stage"], sp["key"], values[sp["key"]])
            if feedback:
                feedback.pushInfo(
                    f"[OVERLAP BATCH] committed {len(usable_specs)} checkpoint(s) in {(time.time()-t0)/60.0:.2f} min."
                )
        except Exception as exc:
            if feedback and feedback.isCanceled():
                raise QgsProcessingException("Processing cancelled during overlap batch.")
            if not allow_legacy_fallback:
                raise QgsProcessingException(
                    f"Native overlap batch failed: {exc}. Completed earlier batches are safely cached. "
                    "Correct the failing geometry and rerun, select the legacy overlap engine, or explicitly enable legacy fallback."
                )
            if feedback:
                feedback.pushWarning(
                    f"[OVERLAP BATCH] Native batch failed ({exc}); using slow cached per-overlay intersections for this batch."
                )
            for sp in usable_specs:
                vals = _legacy_spec_values(blocks, block_areas, dict(sp, fix_legacy=True), context, feedback)
                cache.save(sp["stage"], sp["key"], vals)

# Export checkpoint completion status for run auditing and safe restart decisions.
