                reactivate_confirmed_primary = 1 if (reactivate_evt_primary == 1 and e_evt_raw == 1) else 0
                storage_confirmed_primary = 1 if (storage_evt_primary == 1 and d_evt_raw == 1) else 0
                stabilise_confirmed_primary = 1 if (stabilise_evt_primary == 1 and stabilised_by_rule == 1) else 0
