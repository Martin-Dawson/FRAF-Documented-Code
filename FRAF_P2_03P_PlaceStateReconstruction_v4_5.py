from qgis.core import QgsFeature, QgsWkbTypes, QgsGeometry

# Optional physical spatial copy of a PLACE table, with stringent row-count and non-null attribute round-trip checks.
def _spatialize_table_by_blocks(blocks_poly, table_lyr, context, feedback,
                                block_id_field="BLOCK_ID",
                                out_name="spatialized",
                                flush_every=5000):
    """Create a checked, file-backed spatial copy of a PLACE table.

    The former memory-provider implementation could create the correct geometry and
    schema while silently losing attributes on very large outputs. This implementation
    streams records through QgsVectorFileWriter, verifies row counts and compares a
    populated source sample with the reopened output before returning the layer.
    """
    b = _as_layer(blocks_poly, context)
    t = _as_layer(table_lyr, context)

    if not b or not b.isValid() or b.featureCount() == 0:
        raise QgsProcessingException("_spatialize_table_by_blocks: blocks invalid/empty")
    if QgsWkbTypes.geometryType(b.wkbType()) != QgsWkbTypes.PolygonGeometry:
        raise QgsProcessingException("_spatialize_table_by_blocks: blocks must be polygon geometry")
    if not t or not t.isValid():
        raise QgsProcessingException("_spatialize_table_by_blocks: source table invalid")

    b_idx = b.fields().indexOf(block_id_field)
    t_idx = t.fields().indexOf(block_id_field)
    if b_idx == -1:
        raise QgsProcessingException(f"_spatialize_table_by_blocks: '{block_id_field}' missing on blocks")
    if t_idx == -1:
        raise QgsProcessingException(
            f"_spatialize_table_by_blocks: '{block_id_field}' missing on table '{t.name()}'"
        )

    geom_by_id = {}
    # Build a stable geometry lookup indexed by BLOCK_ID for optional spatial copies.
    for f in b.getFeatures():
        bid = _to_int(f[b_idx])
        g = f.geometry()
        if bid is not None and g and not g.isEmpty():
            geom_by_id[bid] = QgsGeometry(g)
    if not geom_by_id:
        raise QgsProcessingException(f"[SPATIALIZE] {out_name}: no block geometries were indexed")

    # Clone the source schema while rejecting names that GeoPackage treats as duplicates.
    out_fields = QgsFields()
    source_indices = []
    seen = set()
    for i, fld in enumerate(t.fields()):
        key = fld.name().casefold()
        if key in {"fid", "ogc_fid"}:
            continue
        if key in seen:
            raise QgsProcessingException(
                f"[SPATIALIZE] {out_name}: case-insensitive duplicate field '{fld.name()}'"
            )
        seen.add(key)
        out_fields.append(QgsField(fld))
        source_indices.append(i)

    tmp_dir = QgsProcessingUtils.tempFolder()
    tmp_path = os.path.normpath(
        os.path.join(tmp_dir, f"{_safe_layername(out_name)}_{uuid.uuid4().hex}.gpkg")
    )
    layer_name = _safe_layername(out_name)
    opts = QgsVectorFileWriter.SaveVectorOptions()
    opts.driverName = "GPKG"
    opts.layerName = layer_name
    opts.fileEncoding = "UTF-8"
    # This is the initial seed: the file is new, so the writer creates a clean GeoPackage.
    opts.actionOnExistingFile = QgsVectorFileWriter.CreateOrOverwriteFile

    writer = QgsVectorFileWriter.create(
        tmp_path,
        out_fields,
        b.wkbType(),
        b.crs(),
        context.transformContext() if context else QgsCoordinateTransformContext(),
        opts,
    )
    if writer.hasError() != QgsVectorFileWriter.NoError:
        raise QgsProcessingException(
            f"[SPATIALIZE] {out_name}: could not create temporary output: {writer.errorMessage()}"
        )

    source_count = int(t.featureCount())
    written = 0
    missing = 0
    add_failures = 0
    sample_key = None
    sample_expected = None
    sample_names = []

    for row_no, r in enumerate(t.getFeatures(), start=1):
        bid = _to_int(r[t_idx])
        g = geom_by_id.get(bid)
        if g is None:
            missing += 1
            continue

        attrs = [r[i] for i in source_indices]
        nf = QgsFeature(out_fields)
        nf.setGeometry(QgsGeometry(g))
        nf.setAttributes(attrs)
        if not writer.addFeature(nf, QgsFeatureSink.FastInsert):
            add_failures += 1
            if add_failures <= 5 and feedback:
                feedback.reportError(
                    f"[SPATIALIZE] {out_name}: failed inserting row {row_no} for {block_id_field}={bid}"
                )
            continue
        written += 1

        if sample_expected is None:
            # Use a compact populated sample for a post-write attribute comparison.
            for fld, val in zip(out_fields, attrs):
                if val is not None and str(val) != "":
                    sample_names.append(fld.name())
                    if len(sample_names) >= 12:
                        break
            sample_expected = {name: attrs[out_fields.indexOf(name)] for name in sample_names}
            sample_key = (bid, str(r["y1"]) if t.fields().indexOf("y1") >= 0 else "",
                          str(r["y2"]) if t.fields().indexOf("y2") >= 0 else "")

        if feedback and row_no % 100000 == 0:
            feedback.pushInfo(
                f"[SPATIALIZE] {out_name}: processed={row_no:,}/{source_count:,}; "
                f"written={written:,}; missing_geometry={missing:,}; failures={add_failures:,}"
            )

    del writer

    if add_failures:
        raise QgsProcessingException(
            f"[SPATIALIZE] {out_name}: {add_failures:,} output rows failed to write"
        )
    # A spatial output with no geometry for one or more source PLACE rows is unacceptable.
    if missing:
        raise QgsProcessingException(
            f"[SPATIALIZE] {out_name}: {missing:,} rows had no matching block geometry"
        )
    if written != source_count:
        raise QgsProcessingException(
            f"[SPATIALIZE] {out_name}: row-count mismatch source={source_count:,}, written={written:,}"
        )

    out = QgsVectorLayer(f"{tmp_path}|layername={layer_name}", out_name, "ogr")
    if not out.isValid():
        raise QgsProcessingException(f"[SPATIALIZE] {out_name}: temporary layer could not be reopened")
    if int(out.featureCount()) != written:
        raise QgsProcessingException(
            f"[SPATIALIZE] {out_name}: reopened count={out.featureCount():,}, expected={written:,}"
        )

    # Find the sampled record and verify that non-null source attributes survived.
    # Verify an actual populated source record, not merely the presence of output field definitions.
    sample_out = None
    if sample_key is not None:
        bid0, y10, y20 = sample_key
        for f in out.getFeatures():
            if _to_int(f[block_id_field]) != bid0:
                continue
            if out.fields().indexOf("y1") >= 0 and str(f["y1"]) != y10:
                continue
            if out.fields().indexOf("y2") >= 0 and str(f["y2"]) != y20:
                continue
            sample_out = f
            break
    if sample_expected and sample_out is None:
        raise QgsProcessingException(f"[SPATIALIZE] {out_name}: sampled output row was not found")
    if sample_expected:
        mismatches = [
            name for name, expected in sample_expected.items()
            if str(sample_out[name]) != str(expected)
        ]
        if mismatches:
            raise QgsProcessingException(
                f"[SPATIALIZE] {out_name}: attribute QA failed for fields {mismatches[:8]}"
            )

    if feedback:
        feedback.pushInfo(
            f"[SPATIALIZE] {out_name}: verified {written:,} rows and {len(out_fields)} attributes"
        )
    return out


# Quote SQLite identifiers defensively (names are identifiers, never SQL string literals).
def _sql_ident(name):
    """Quote a SQLite/GeoPackage identifier."""
    return '"' + str(name).replace('"', '""') + '"'


# Build a read-only GeoPackage feature VIEW joined by BLOCK_ID, reusing KM_blocks geometry instead of copying wide attributes.
def _create_registered_spatial_view(
    gpkg_path,
    source_table,
    blocks_table,
    view_name,
    join_field="BLOCK_ID",
    source_count=None,
    feedback=None,
):
    """Register a read-only GeoPackage feature view without duplicating attributes.

    The view carries the source table's own unique ``fid`` and joins the polygon
    geometry from ``KM_blocks`` using BLOCK_ID. This avoids the slow and unreliable
    physical duplication of millions of wide interval rows.
    """
    if not os.path.exists(gpkg_path):
        raise QgsProcessingException(f"[SPATIAL VIEW] GeoPackage not found: {gpkg_path}")

    con = sqlite3.connect(gpkg_path, timeout=120.0)
    try:
        con.execute("PRAGMA busy_timeout=120000")
        con.execute("PRAGMA foreign_keys=OFF")

        source_info = con.execute(
            f"PRAGMA table_info({_sql_ident(source_table)})"
        ).fetchall()
        block_info = con.execute(
            f"PRAGMA table_info({_sql_ident(blocks_table)})"
        ).fetchall()
        source_cols = [str(r[1]) for r in source_info]
        block_cols = [str(r[1]) for r in block_info]

        if not source_cols:
            raise QgsProcessingException(
                f"[SPATIAL VIEW] Source table '{source_table}' does not exist or has no fields"
            )
        if "fid" not in {c.casefold(): c for c in source_cols}:
            raise QgsProcessingException(
                f"[SPATIAL VIEW] Source table '{source_table}' has no GeoPackage fid field"
            )
        if join_field.casefold() not in {c.casefold(): c for c in source_cols}:
            raise QgsProcessingException(
                f"[SPATIAL VIEW] '{join_field}' missing from source table '{source_table}'"
            )
        if join_field.casefold() not in {c.casefold(): c for c in block_cols}:
            raise QgsProcessingException(
                f"[SPATIAL VIEW] '{join_field}' missing from geometry table '{blocks_table}'"
            )

        geom_row = con.execute(
            "SELECT column_name, geometry_type_name, srs_id, z, m "
            "FROM gpkg_geometry_columns WHERE table_name=?",
            (blocks_table,),
        ).fetchone()
        if not geom_row:
            raise QgsProcessingException(
                f"[SPATIAL VIEW] Geometry metadata not found for '{blocks_table}'"
            )
        geom_col, geom_type, srs_id, z, m = geom_row

        contents_row = con.execute(
            "SELECT min_x, min_y, max_x, max_y "
            "FROM gpkg_contents WHERE table_name=?",
            (blocks_table,),
        ).fetchone()
        min_x, min_y, max_x, max_y = contents_row if contents_row else (None, None, None, None)

        existing = con.execute(
            "SELECT type FROM sqlite_master WHERE name=?",
            (view_name,),
        ).fetchone()

        # Remove stale metadata first, then remove an existing table or view.
        # Remove old feature-view registration before re-registering the replacement.
        con.execute("DELETE FROM gpkg_geometry_columns WHERE table_name=?", (view_name,))
        con.execute("DELETE FROM gpkg_contents WHERE table_name=?", (view_name,))
        if con.execute(
            "SELECT 1 FROM sqlite_master WHERE type='table' AND name='gpkg_ogr_contents'"
        ).fetchone():
            con.execute("DELETE FROM gpkg_ogr_contents WHERE table_name=?", (view_name,))

        if existing:
            if existing[0] == "view":
                con.execute(f"DROP VIEW {_sql_ident(view_name)}")
            elif existing[0] == "table":
                con.execute(f"DROP TABLE {_sql_ident(view_name)}")

        # Preserve the source fid as the view feature id. Exclude any accidental
        # geometry field from the source table and append the KM_blocks geometry.
        select_cols = []
        for col in source_cols:
            if col.casefold() == str(geom_col).casefold():
                continue
            select_cols.append(f"l.{_sql_ident(col)} AS {_sql_ident(col)}")
        # Spatial views borrow the single authoritative KM_blocks geometry via BLOCK_ID.
        select_cols.append(f"b.{_sql_ident(geom_col)} AS {_sql_ident(geom_col)}")

        sql = (
            f"CREATE VIEW {_sql_ident(view_name)} AS "
            f"SELECT {', '.join(select_cols)} "
            f"FROM {_sql_ident(source_table)} AS l "
            f"JOIN {_sql_ident(blocks_table)} AS b "
            f"ON l.{_sql_ident(join_field)} = b.{_sql_ident(join_field)}"
        )
        con.execute(sql)

        con.execute(
            """
            INSERT INTO gpkg_contents
            (table_name, data_type, identifier, description, last_change,
             min_x, min_y, max_x, max_y, srs_id)
            VALUES (?, 'features', ?, ?, strftime('%Y-%m-%dT%H:%M:%fZ','now'),
                    ?, ?, ?, ?, ?)
            """,
            (
                view_name,
                view_name,
                f"Virtual spatial join of {source_table} to {blocks_table}; no duplicated attributes",
                min_x, min_y, max_x, max_y, srs_id,
            ),
        )
        con.execute(
            """
            INSERT INTO gpkg_geometry_columns
            (table_name, column_name, geometry_type_name, srs_id, z, m)
            VALUES (?, ?, ?, ?, ?, ?)
            """,
            (view_name, geom_col, geom_type, srs_id, z, m),
        )

        if con.execute(
            "SELECT 1 FROM sqlite_master WHERE type='table' AND name='gpkg_ogr_contents'"
        ).fetchone():
            try:
                con.execute(
                    "INSERT OR REPLACE INTO gpkg_ogr_contents(table_name, feature_count) VALUES (?, ?)",
                    (view_name, int(source_count) if source_count is not None else None),
                )
            except Exception:
                pass

        # Add ordinary join indexes. They do not duplicate the interval attributes
        # and materially improve view access.
        safe_src_idx = re.sub(r"[^0-9A-Za-z_]+", "_", f"idx_{source_table}_{join_field}")[:60]
        safe_blk_idx = re.sub(r"[^0-9A-Za-z_]+", "_", f"idx_{blocks_table}_{join_field}")[:60]
        con.execute(
            f"CREATE INDEX IF NOT EXISTS {_sql_ident(safe_src_idx)} "
            f"ON {_sql_ident(source_table)}({_sql_ident(join_field)})"
        )
        con.execute(
            f"CREATE INDEX IF NOT EXISTS {_sql_ident(safe_blk_idx)} "
            f"ON {_sql_ident(blocks_table)}({_sql_ident(join_field)})"
        )

        # Direct SQL QA: compare one populated source record with the view.
        sample = con.execute(
            f"SELECT fid FROM {_sql_ident(source_table)} ORDER BY fid LIMIT 1"
        ).fetchone()
        if sample:
            fid0 = sample[0]
            src_sample = con.execute(
                f"SELECT * FROM {_sql_ident(source_table)} WHERE fid=?",
                (fid0,),
            ).fetchone()
            view_sample = con.execute(
                f"SELECT {', '.join(_sql_ident(c) for c in source_cols)} "
                f"FROM {_sql_ident(view_name)} WHERE fid=?",
                (fid0,),
            ).fetchone()
            if src_sample is None or view_sample is None or tuple(src_sample) != tuple(view_sample):
                raise QgsProcessingException(
                    f"[SPATIAL VIEW] Attribute QA failed for '{view_name}' at fid={fid0}"
                )

        con.commit()
    finally:
        con.close()

    # Lightweight OGR/QGIS validation. Do not call featureCount(), which would
    # force a full scan of a million-row virtual view.
    uri = f"{gpkg_path}|layername={view_name}"
    lyr = QgsVectorLayer(uri, view_name, "ogr")
    if not lyr.isValid():
        raise QgsProcessingException(
            f"[SPATIAL VIEW] Registered view could not be opened by QGIS: {view_name}"
        )
    # Inspect one feature only: calling featureCount() on a million-row join view could trigger an expensive full scan.
    first = next(lyr.getFeatures(QgsFeatureRequest().setLimit(1)), None)
    if first is None:
        raise QgsProcessingException(f"[SPATIAL VIEW] Registered view is empty: {view_name}")
    populated = 0
    for fld in lyr.fields():
        if fld.name().casefold() in {"fid", str(geom_col).casefold()}:
            continue
        try:
            val = first[fld.name()]
        except Exception:
            continue
        if val is not None and str(val) != "":
            populated += 1
    if populated == 0:
        raise QgsProcessingException(
            f"[SPATIAL VIEW] View opened but sampled attributes were empty: {view_name}"
        )

    if feedback:
        feedback.pushInfo(
            f"[SPATIAL VIEW] Created and verified '{view_name}' from '{source_table}' "
            f"without duplicating {source_count if source_count is not None else 'unknown'} rows."
        )
    return uri


