            ea_prepared = _prep_poly(ea_layer, context, feedback)
            if not ea_prepared or not ea_prepared.isValid():
                feedback.reportError(f"[EA] Could not prepare {ea_layer.name()}; storing zero checkpoints.")
                for prefix in ("E", "D", "S"):
                    overlap_cache.save("EA", f"{prefix}_{ii:03d}", {})
